test('complete door survey explains unavailable search and keeps actions near the result title', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '새 설문 시작', exact: true }).click()
  await page.getByRole('radio').first().check()
  await page.getByLabel('공간', { exact: true }).selectOption('entrance')
  await page.getByLabel('시설물', { exact: true }).selectOption('door')
  await page.getByLabel('증상', { exact: true }).selectOption('opening-function')
  await page.getByRole('button', { name: '저장하고 설문으로' }).click()
  for (const [name, value] of [['immediate-danger', 'NO'], ['shared-use', 'HOUSEHOLD'], ['detail-opening-function', 'CLOSE'], ['disaster-context', 'NO']]) {
    const saved = page.waitForResponse(r => r.url().endsWith('/context') && r.request().method() === 'PUT')
    await page.locator(`input[name="${name}"][value="${value}"]`).check()
    expect((await saved).status()).toBe(200)
  }
  await page.getByRole('button', { name: '안내 결과 확인', exact: true }).click()
  await expect(page.getByRole('heading', { name: '지금은 안내할 수 없어요' })).toBeVisible()
  await expect(page.getByText(/OpenAI 연결이 꺼져 있어/)).toBeVisible()
  await expect(page.getByText('이런 경우에는 보수를 검토할 수 있어요')).toHaveCount(0)
  await expect(page.getByRole('region', { name: '설문 상담 관리' }).getByRole('button', { name: '상담 종료' })).toBeInViewport()
  const actions = page.getByRole('navigation', { name: '설문 작업' })
  await expect(actions.getByRole('button', { name: '새 설문 시작' })).toBeInViewport()
  await accessible(page)
  await page.screenshot({ path: '../artifacts/chat-workspace-20261118/' + test.info().project.name + '-door-result.png' })
  await actions.getByRole('button', { name: '새 설문 시작' }).click()
  await expect(page).toHaveURL('/select')
})
